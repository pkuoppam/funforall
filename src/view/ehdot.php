<h1>Sopimusehdot</h1>

<p>
1. Vuokrattava tuote maksetaan etukäteen. 
Maksun viestikenttään tulee 
ilmoittaa sekä vuokraajan nimi että puhelinnumero.<br><br>
2. Vuokraaja ei saa jälleenvuokrata tuotteita.<br><br>
3. Vuokraaja sitoutuu noudattamaan seuraavia käyttöohjeita:<br><br>
Sup-lautailu/Kanootin käyttö tapahtuu aina vuokraajan omalla vastuulla.
Vuokraaja huolehtii itse omasta vakuutusturvasta. Vuokraaja on velvollinen 
todistamaan henkilöllisyytensä pyydettäessä. Mikäli vuokraaja luovuttaa 
välineet kolmannen osapuolen käyttöön, vuokraaja on edelleen vastuussa 
vuokrausehtojen täyttymisestä.Vuokraaja on velvollinen käsittelemään 
vuokraamiaan välineitä huolellisesti ja siten,että ne eivät vahingoitu tai katoa. 
Välineet tarkistetaan yhdessä vuokraajan kanssa ennen ja jälkeen vuokrauksen. 
Vuokrattuja välineitä saa käyttää vain suppailuun soveltuvissa, riittävän syvissä vesissä, 
joissa ei ole kivikkoja tai muita esteitä, jotka voivat vahingoittaa välineitä. <br><br>
Vuokraaja on velvollinen viipymättä ilmoittamaan vuokranantajalle välineiden 
katoamisesta,välineille aiheutuneista vahingoista tai välineissä ilmenevistä vioista.
Vuokraaja on velvollinen korvaamaan vuokravälineiden katoamisesta tai vahingoittumisesta aiheutuneen 
vahingon niiden käyvän arvon mukaisesti.<br><br> Välineet on palautettava viimeistään vuokrausajan päättyessä.
Mikäli vuokraaja palauttaa vuokravälineet myöhässä tai jättää ne kokonaan palauttamatta,
vuokranantaja voi periä lisävuokraa palautus- tai löytöhetkeen saakka.
</p>

<h2>Laitteen palautus</h2>

<p>Vuokrattava tuote palautetaan puhtaana ja kuivana, kantopussiin pakattuna oheistarvikkeineen.
   Likaisen tuotteen palautuksesta veloitamme 50€ siivousmaksun.
   Asiakas huolehtii kuljetuksesta ja palautuksesta sovittuna ajankohtana.
   Palautuksen viivästyksestä veloitetaan kaksinkertainen vuorokausivuokra 
   ylimeneviltä vuorokausilta. Asiakas on vastuullinen korvaamaan rikkoutuneen tai kadonneen laitteen.
   Varkaus tai vahinkotapauksissa yhteys vuokranantajaan välittömästi.
</p>
